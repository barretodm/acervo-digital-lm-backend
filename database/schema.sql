CREATE TABLE IF NOT EXISTS public.obras (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT,
  tipo TEXT NOT NULL CHECK (tipo IN ('quadro', 'escultura')),
  artista TEXT NOT NULL,
  tecnica TEXT NOT NULL,
  ano INTEGER NOT NULL CHECK (ano >= 1900),
  largura_cm NUMERIC(10, 2) NOT NULL CHECK (largura_cm > 0),
  altura_cm NUMERIC(10, 2) NOT NULL CHECK (altura_cm > 0),
  profundidade_cm NUMERIC(10, 2),
  descricao TEXT,
  valor NUMERIC(12, 2) CHECK (valor IS NULL OR valor >= 0),
  status TEXT NOT NULL DEFAULT 'aberto'
    CHECK (status IN ('aberto', 'em_conversa', 'reservado', 'vendido')),
  ativa BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (tipo = 'escultura' AND profundidade_cm IS NOT NULL AND profundidade_cm > 0)
    OR (tipo = 'quadro' AND profundidade_cm IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS public.tecnicas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.obra_tecnicas (
  obra_id BIGINT NOT NULL REFERENCES public.obras (id) ON DELETE CASCADE,
  tecnica_id BIGINT NOT NULL REFERENCES public.tecnicas (id) ON DELETE CASCADE,
  PRIMARY KEY (obra_id, tecnica_id)
);

CREATE TABLE IF NOT EXISTS public.fotos_obra (
  id UUID PRIMARY KEY,
  obra_id BIGINT NOT NULL REFERENCES public.obras (id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  capa BOOLEAN NOT NULL DEFAULT FALSE,
  ordem INTEGER NOT NULL CHECK (ordem >= 0)
);

CREATE TABLE IF NOT EXISTS public.interesses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  obra_id BIGINT NOT NULL REFERENCES public.obras (id),
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  telefone TEXT NOT NULL,
  mensagem TEXT,
  consentimento_lgpd BOOLEAN NOT NULL CHECK (consentimento_lgpd),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS obras_ativas_criado_em_idx
  ON public.obras (ativa, criado_em DESC);

CREATE INDEX IF NOT EXISTS obra_tecnicas_tecnica_id_idx
  ON public.obra_tecnicas (tecnica_id);

CREATE INDEX IF NOT EXISTS fotos_obra_obra_ordem_idx
  ON public.fotos_obra (obra_id, ordem);

CREATE UNIQUE INDEX IF NOT EXISTS fotos_obra_uma_capa_por_obra_idx
  ON public.fotos_obra (obra_id)
  WHERE capa;

CREATE INDEX IF NOT EXISTS interesses_obra_criado_em_idx
  ON public.interesses (obra_id, criado_em DESC);

CREATE OR REPLACE FUNCTION public.definir_atualizado_em()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.atualizado_em = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS obras_definir_atualizado_em ON public.obras;
CREATE TRIGGER obras_definir_atualizado_em
  BEFORE UPDATE ON public.obras
  FOR EACH ROW
  EXECUTE FUNCTION public.definir_atualizado_em();

